function cloneData(obj) {
  return JSON.parse(JSON.stringify(obj));
}

function normalizeKey(value) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
    .toUpperCase();
}

function localDbSafe() {
  try {
    if (typeof getDB === 'function') return getDB();
    return JSON.parse(localStorage.getItem('khonfacil_db_v2') || '{}');
  } catch (e) {
    return {};
  }
}

function labelStatus(status) {
  const key = normalizeKey(status);
  if (key === 'EM ABERTO') return 'Em Aberto';
  if (key === 'ACORDO FIRMADO') return 'Acordo Firmado';
  if (key === 'INSUCESSO') return 'Insucesso';
  if (key === 'AJUIZADO') return 'Ajuizado';
  if (key === 'ADIMPLENTE') return 'Adimplente';
  return status || 'Não informado';
}

function calcLocalDashboardRisk(cota) {
  const dias = Number(cota.diasAtraso || cota.Dias_Em_Atraso_Inicial || 0);
  const parcelas = Number(cota.parcelasAtrasadas || 0);
  let score = 0;
  if (cota.bemEntregue === true || cota.bemEntregue === 'true') score += 30;
  score += Math.min(dias / 180 * 35, 35);
  score += Math.min(parcelas * 7, 28);
  if (normalizeKey(cota.status) === 'AJUIZADO') score += 12;
  score = Math.min(Math.round(score), 100);
  if (score >= 70) return 'Alto Risco';
  if (score >= 40) return 'Médio Risco';
  return 'Baixo Risco';
}

function pushOrAddStatus(data, label, value) {
  let item = data.status_dist.find(s => normalizeKey(s.label) === normalizeKey(label));
  if (!item) {
    item = { label, value: 0, color: 'rgba(10,132,200,0.75)' };
    data.status_dist.push(item);
  }
  item.value += Number(value || 0);
}

function monthLabelFromDate(dateStr) {
  const d = new Date(dateStr);
  if (Number.isNaN(d.getTime())) return null;
  const meses = ['Jan','Fev','Mar','Abr','Mai','Jun','Jul','Ago','Set','Out','Nov','Dez'];
  return `${meses[d.getMonth()]}/${String(d.getFullYear()).slice(-2)}`;
}

function addAssessoriaToDashboard(data, a) {
  const name = String(a.nome || a.Nome_Assessoria || '').trim().toUpperCase();
  if (!name) return;
  const existing = data.assessorias.find(x => normalizeKey(x.nome) === normalizeKey(name));
  if (existing && a.source !== 'local') return;

  const total = Number(a.total_casos || a.totalCasos || a.casos || 0);
  const acordos = Number(a.acordos || 0);
  const insucesso = Number(a.insucesso || 0);
  const ajuizado = Number(a.ajuizado || 0);
  const emAberto = Number(a.em_aberto || a.emAberto || Math.max(total - acordos - insucesso - ajuizado, 0));
  const valorInad = Number(a.valor_inadimplente || a.valorInadimplente || 0);
  const valorRec = Number(a.valor_recuperado || a.valorRecuperado || 0);
  const taxaRec = total ? (acordos / total * 100) : Number(a.taxaRecuperacao || a.taxa_recuperacao || 0);
  const taxaIns = total ? (insucesso / total * 100) : Number(a.taxaInsucesso || a.taxa_insucesso || a.insucesso || 0);
  const efic = valorInad ? (valorRec / valorInad * 100) : Number(a.eficienciaFinanceira || a.eficiencia_financeira || 0);
  const score = Number(a.score_composto || a.score || 35);
  const faixa = score >= 75 ? 'ELITE' : score >= 55 ? 'ALTO' : score >= 35 ? 'MÉDIO' : 'BÁSICO';
  const comissao = Number(a.comissao_pct || a.comissao || (score >= 55 ? 6 : score >= 35 ? 4.5 : 3));

  const obj = {
    nome: name,
    nome_curto: a.nome_curto || name.split(' ')[0],
    total_casos: total,
    acordos: acordos,
    insucesso: insucesso,
    ajuizado: ajuizado,
    em_aberto: emAberto,
    valor_inadimplente: valorInad,
    valor_recuperado: valorRec,
    atraso_medio: Number(a.atraso_medio || a.atrasoMedio || 0),
    prejuizo_total: Math.max(valorInad - valorRec, 0),
    taxa_recuperacao: taxaRec,
    taxa_insucesso: taxaIns,
    eficiencia_financeira: efic,
    score_composto: score,
    faixa,
    comissao_pct: comissao,
    remuneracao: valorRec * comissao / 100,
    cor: a.cor || '#0060a0',
    local: true
  };

  if (existing) Object.assign(existing, obj);
  else data.assessorias.push(obj);
}

function mergeLocalChanges(data) {
  const db = localDbSafe();
  if (!db || Object.keys(db).length === 0) return data;

  const baseAssessoriaKeys = new Set(data.assessorias.map(a => normalizeKey(a.nome)));

  (db.assessorias || []).forEach(a => {
    if (a.source === 'local' || !baseAssessoriaKeys.has(normalizeKey(a.nome))) addAssessoriaToDashboard(data, a);
  });

  const localCotas = (db.cotas || []).filter(c => c.source === 'local');
  localCotas.forEach(c => {
    const status = labelStatus(c.status);
    const valor = Number(c.saldoDevedor || c.valorInadimplente || c.valorCredito || 0);
    const recuperado = normalizeKey(c.status) === 'ACORDO FIRMADO' ? valor : 0;
    const inad = ['EM ABERTO','AJUIZADO'].includes(normalizeKey(c.status)) ? 1 : 0;

    data.kpis.total_registros += 1;
    data.kpis.valor_inadimplente_total += valor;
    data.kpis.valor_recuperado_total += recuperado;
    pushOrAddStatus(data, status, 1);

    const regionName = String(c.regiao || 'NÃO INFORMADO').toUpperCase();
    let reg = data.regional.find(r => normalizeKey(r.nome_full || r.nome) === normalizeKey(regionName));
    if (!reg) {
      reg = { nome: regionName.charAt(0)+regionName.slice(1).toLowerCase(), nome_full: regionName, volume: 0, taxa_rec: 0, inadimplencia: 0, atraso: 0, score_risco: 0, total_devido: 0, valor_recuperado: 0, eficiencia_financeira: 0, prejuizo_liquido: 0 };
      data.regional.push(reg);
    }
    const prevVolume = reg.volume || 0;
    reg.volume += 1;
    reg.total_devido += valor;
    reg.valor_recuperado += recuperado;
    reg.prejuizo_liquido = Math.max((reg.prejuizo_liquido || 0) + valor - recuperado, 0);
    reg.atraso = prevVolume ? ((reg.atraso * prevVolume) + Number(c.diasAtraso || 0)) / reg.volume : Number(c.diasAtraso || 0);
    reg.inadimplencia = reg.volume ? (((reg.inadimplencia || 0) * prevVolume / 100 + inad) / reg.volume * 100) : 0;
    reg.taxa_rec = reg.volume ? (((reg.taxa_rec || 0) * prevVolume / 100 + (normalizeKey(c.status) === 'ACORDO FIRMADO' ? 1 : 0)) / reg.volume * 100) : 0;
    reg.eficiencia_financeira = reg.total_devido ? reg.valor_recuperado / reg.total_devido * 100 : 0;

    const riskLabel = calcLocalDashboardRisk(c);
    let risk = data.faixa_risco.find(r => normalizeKey(r.label) === normalizeKey(riskLabel));
    if (risk) risk.contratos = Number(risk.contratos || 0) + 1;

    const mes = monthLabelFromDate(c.vencimento || new Date().toISOString());
    if (mes) {
      let t = data.temporal.find(x => x.mes === mes);
      if (!t) {
        t = {mes, inadimplencia: 0, recuperacao: 0, volume: 0, total_devido: 0, arrecadado: 0};
        data.temporal.push(t);
      }
      const pv = t.volume || 0;
      t.volume += 1;
      t.total_devido += valor;
      t.arrecadado += recuperado;
      t.inadimplencia = t.volume ? (((t.inadimplencia || 0) * pv / 100 + inad) / t.volume * 100) : 0;
      t.recuperacao = t.volume ? (((t.recuperacao || 0) * pv / 100 + (normalizeKey(c.status)==='ACORDO FIRMADO' ? 1 : 0)) / t.volume * 100) : 0;
    }
  });

  const emAberto = data.status_dist.find(s => normalizeKey(s.label) === 'EM ABERTO')?.value || 0;
  const ajuizado = data.status_dist.find(s => normalizeKey(s.label) === 'AJUIZADO')?.value || 0;
  const acordos = data.status_dist.find(s => normalizeKey(s.label) === 'ACORDO FIRMADO')?.value || 0;
  data.kpis.total_assessorias = data.assessorias.length;
  data.kpis.inadimplencia_pct = data.kpis.total_registros ? ((emAberto + ajuizado) / data.kpis.total_registros * 100) : 0;
  data.kpis.recuperacao_pct = data.kpis.total_registros ? (acordos / data.kpis.total_registros * 100) : 0;

  const totalRisk = data.faixa_risco.reduce((s, r) => s + Number(r.contratos || 0), 0);
  if (totalRisk) data.faixa_risco.forEach(r => r.value = Number((Number(r.contratos || 0) / totalRisk * 100).toFixed(1)));

  data.assessorias.sort((a,b) => (b.score_composto || 0) - (a.score_composto || 0));
  data.regional.sort((a,b) => (b.volume || 0) - (a.volume || 0));
  return data;
}

window.buildDashboardData = function buildDashboardData() {
  return mergeLocalChanges(cloneData(window.KHON_DASHBOARD_BASE));
};
